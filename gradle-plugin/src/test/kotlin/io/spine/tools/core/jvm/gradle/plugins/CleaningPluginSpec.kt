import org.junit.jupiter.api.io.TempDir

@DisplayName("`CleaningPlugin` should")
internal class CleaningPluginSpec {

    companion object {

        lateinit var project: Project

        /**
         * The names of the tasks Gradle created while the project was configured.
         */
        lateinit var createdOnConfiguration: List<String>

        @BeforeAll
        @JvmStatic
        fun createProject(@TempDir tempDir: File) {
            project = StubProject.createIn(tempDir)
                .withMavenRepositories()
                .get()
            val created = mutableListOf<String>()
            project.tasks.configureEach { created.add(it.name) }

            val plugins = project.pluginManager
            plugins.apply(GradleProject.javaPlugin)
            plugins.apply("com.google.protobuf")
            plugins.apply(CoreJvmPlugin::class.java)

            evaluate(project)
            createdOnConfiguration = created.toList()
        }
    }

    @Test
    fun `not create 'preClean' and 'clean' while the project is configured`() {
        createdOnConfiguration shouldNotContainAnyOf listOf(preClean.value(), clean.value())
    }

    @Test
    fun `make 'clean' depend on 'preClean'`() {
        val cleanTask = task(clean.value())
        val dependencies = cleanTask.taskDependencies.getDependencies(cleanTask).map { it.name }
        dependencies shouldContain preClean.value()
    }

    @Test
    fun `add 'preClean' to the Spine task group`() {
        val preCleanTask = task(preClean.value())
        preCleanTask.group shouldBe SpineTaskGroup.name
        preCleanTask.description shouldBe "Deletes the temporary directories generated by Spine"
    }

    @Test
    fun `delete temporary artifact directories when 'preClean' runs`() {
        val tempArtifacts = project.projectDir.resolve("temp-artifacts")
        tempArtifacts.resolve("generated.txt").apply {
            parentFile.mkdirs()
            writeText("To be deleted by `preClean`.")
        }
        tempArtifacts.shouldExist()
        project.coreJvmOptions.tempArtifactDirs = listOf(tempArtifacts.path)

        val preCleanTask = task(preClean.value())
        preCleanTask.actions.forEach { it.execute(preCleanTask) }

        tempArtifacts.shouldNotExist()
    }
}

private fun task(name: String): Task = CleaningPluginSpec.project.tasks.getByName(name)
