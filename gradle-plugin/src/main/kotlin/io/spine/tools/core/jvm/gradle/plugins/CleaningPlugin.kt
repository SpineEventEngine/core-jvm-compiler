package io.spine.tools.core.jvm.gradle.plugins

import io.spine.io.deleteRecursively
import io.spine.tools.core.jvm.gradle.CoreJvmCompilerTaskName.Companion.preClean
import io.spine.tools.core.jvm.gradle.TempArtifactDirs
import io.spine.tools.gradle.task.BaseTaskName.clean
import io.spine.tools.gradle.task.SpineTaskGroup
import java.io.File
import org.gradle.api.Action
import org.gradle.api.Plugin
import org.gradle.api.Project
import org.gradle.api.Task

/**
 * Plugin that performs additional cleanup of the Spine-generated folders.
 *
 * Adds a custom `preClean` task, which is executed before the `clean` task.
 *
 * Neither task is created while the project is configured: `preClean` is registered,
 * and `clean` gets the dependency on it whenever Gradle creates `clean`.
 */
public class CleaningPlugin : Plugin<Project> {

    override fun apply(project: Project) {
        val tasks = project.tasks
        val preCleanTask = tasks.register(preClean.value()) { task ->
            task.group = SpineTaskGroup.name
            task.description = "Deletes the temporary directories generated by Spine"
            task.doLast(PreCleanAction(project))
        }
        // Filtering by name does not create `clean`, and also covers the case of
        // `clean` being registered after this plugin is applied.
        val cleanTask = clean.value()
        tasks.named { it == cleanTask }.configureEach {
            it.dependsOn(preCleanTask)
        }
        project.logger.debug("Pre-clean phase initialized: `{}`.", preCleanTask)
    }
}

/**
 * Recursively deletes [temp. artifact directories][TempArtifactDirs] in
 * the given project.
 */
private class PreCleanAction(private val project: Project) : Action<Task> {

    override fun execute(task: Task) {
        val logger = project.logger
        val dirsToClean = TempArtifactDirs.getFor(project)
        if (logger.isDebugEnabled) {
            val dirs = dirsToClean.joinToString()
            logger.debug("Pre-clean: deleting the directories (`{}`).", dirs)
        }
        dirsToClean.map(File::toPath)
            .forEach { dir ->
                logger.debug("Deleting directory `{}`...", dir)
                deleteRecursively(dir)
            }
    }
}
